// Loupe (cocher des fiches et des formules, les réviser) et zone d'écriture : node tools/loupe_test.mjs /tmp/captures
// (serveur lancé avant : npm run serve).
import { chromium, devices } from 'playwright';
const shots = process.argv[2] || '/tmp/shots';
const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
const ctx = await browser.newContext({ ...devices['iPhone 13'], defaultBrowserType: undefined });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => m.type() === 'error' && errors.push(m.text()));
const text = async sel => (await page.textContent(sel)).replace(/\s+/g, ' ').trim();
const fail = m => { console.log('ÉCHEC :', m); process.exitCode = 1; };
await page.goto('http://localhost:8765/');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('fc-formules-matiere-v1', 'maths'); });
await page.reload();
await page.waitForSelector('#go-all');

await page.click('#btn-search');
await page.waitForSelector('[data-group="BCPST1"]');
await page.click('[data-show]');
await page.click('input.pick >> nth=0');
await page.click('input.pick >> nth=2');
await page.click('[data-group="Formulaire"]');
await page.click('[data-show="F-DL"]');
await page.click('[data-pickall="F-DL"]');
await page.screenshot({ path: `${shots}/l1-loupe.png`, fullPage: true });
const banner = await text('.pick-banner');
console.log('bandeau :', banner);
if (!banner.includes('14 cartes cochées')) fail('14 cartes attendues (2 fiches + 12 DL)');

await page.click('[data-mode="az"]');
await page.click('[data-letter="F"]');
console.log('lettre F :', (await text('.terms')).slice(0, 120));
await page.click('.terms .term-link');
await page.waitForSelector('#def-pick');
await page.click('#def-pick');
await page.screenshot({ path: `${shots}/l2-modale.png` });
await page.click('#def-close');
if (!(await text('.pick-banner')).includes('15 cartes cochées')) fail('15 cartes après la modale');

await page.click('#btn-back');
console.log('accueil :', await text('#go-picked'));
await page.click('#go-picked');
await page.waitForSelector('#cards-go, #qcm-go, #reveal');
if (await page.$('#cards-go')) await page.click('#cards-go');
await page.waitForSelector('#draw-toggle');
await page.click('#draw-toggle');
const cv = await page.$('canvas.sketch');
const b = await cv.boundingBox();
await page.mouse.move(b.x + 20, b.y + 30);
await page.mouse.down();
for (let i = 1; i <= 20; i++) await page.mouse.move(b.x + 20 + 10 * i, b.y + 30 + 8 * Math.sin(i));
await page.mouse.up();
await page.mouse.move(b.x + 40, b.y + 100);
await page.mouse.down();
await page.mouse.move(b.x + 200, b.y + 120);
await page.mouse.up();
await page.screenshot({ path: `${shots}/l3-ecriture.png` });
const n = await page.evaluate(() => session.sketch.strokes.length);
if (n !== 2) fail(`2 traits attendus, ${n}`);
await page.click('#draw-undo');
await page.click('#reveal');
await page.waitForSelector('canvas.sketch.done');
await page.screenshot({ path: `${shots}/l4-comparaison.png` });
const ink = await page.evaluate(() => {
  const c = document.querySelector('canvas.sketch.done');
  const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
  let k = 0;
  for (let i = 3; i < d.length; i += 4) k += d[i] > 0;
  return k;
});
console.log('pixels encrés après retournement :', ink);
if (!ink) fail('brouillon non redessiné');
await page.click('.grade .good');
if (await page.$('canvas.sketch') && await page.evaluate(() => session.sketch.strokes.length)) fail('brouillon non vidé à la carte suivante');
const st = await page.evaluate(() => JSON.parse(localStorage.getItem('fc-formules-maths-v1')));
console.log('cochées enregistrées :', st.picked.length, '· zone d’écriture mémorisée :', st.settings.draw);
console.log('erreurs :', errors);
if (errors.length) process.exitCode = 1;
await browser.close();
